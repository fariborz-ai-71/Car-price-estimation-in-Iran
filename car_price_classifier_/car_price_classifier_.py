import pandas as pd
import numpy as np

# 1. بارگذاری دیتاست
try:
    df = pd.read_csv('IKCO_Saipa_Cars_final.csv')
    print("✅ دیتاست با موفقیت بارگذاری شد.")
except FileNotFoundError:
    print("❌ خطا: فایل 'IKCO_Saipa_Cars_final.csv' پیدا نشد. لطفا مسیر فایل را بررسی کنید.")
    # خروج یا ایجاد یک DataFrame آزمایشی
    exit()

# --- تحلیل توزیع قیمت برای تعیین مرزها ---

# محاسبه کوانتایل 33.3% و 66.7% برای تقسیم داده‌ها به 3 بخش مساوی (بر اساس تعداد نمونه)
Q1 = df['price'].quantile(0.333)
Q2 = df['price'].quantile(0.667)

# 2. تعریف مرزهای کلاس‌بندی (Bins) و لیبل‌ها
# مرزها شامل حداقل و حداکثر قیمت دیتاست هستند. (+/- 1 برای اطمینان از قرارگیری Min/Max در داخل بازه‌ها)
bins = [
    df['price'].min() - 1,  # پایین‌ترین مرز
    Q1,                     # مرز بین اقتصادی و متوسط
    Q2,                     # مرز بین متوسط و گران
    df['price'].max() + 1   # بالاترین مرز
]

labels_fa = ['اقتصادی', 'متوسط', 'گران']

print("-" * 40)
print(f"💰 مرزهای قیمت (بر اساس کوانتایل‌ها):")
print(f"   - مرز اقتصادی: تا {Q1:,.0f} تومان")
print(f"   - مرز متوسط: از {Q1:,.0f} تا {Q2:,.0f} تومان")
print(f"   - مرز گران: بالاتر از {Q2:,.0f} تومان")
print("-" * 40)

# 3. اعمال کلاس‌بندی با استفاده از pd.cut
# این تابع قیمت‌ها را در بازه‌های تعریف شده قرار داده و لیبل مربوطه را به آن‌ها اختصاص می‌دهد.
df['price_category'] = pd.cut(
    df['price'],
    bins=bins,
    labels=labels_fa,
    include_lowest=True, # شامل شدن کمترین مقدار
    right=True           # بازه‌ها از راست بسته هستند
)

# 4. نمایش توزیع نهایی کلاس‌ها
print("📊 توزیع خودروها در کلاس‌های جدید:")
display(df['price_category'].value_counts().to_frame())

# 5. ذخیره‌سازی دیتاست نهایی
output_filename = 'IKCO_Saipa_Cars_with_Classes.csv'
df.to_csv(output_filename, index=False, encoding='utf-8')

print("-" * 40)
print(f"💾 دیتاست نهایی با ستون 'price_category' در فایل '{output_filename}' ذخیره شد.")
print("نمایش ۵ ردیف اول دیتاست جدید:")
display(df[['price', 'price_category']].head())

